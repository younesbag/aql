-- 0002 — ركائز المحتوى قابلة للإعداد
-- ───────────────────────────────────────────────────────────
-- كان قيد posts_content_pillar_chk يحصر content_pillar في أربع قيم حرفية تخصّ المالك
-- الأصلي. الركائز الآن تُعرَّف في data/profile.json (2–8 ركائز بمفاتيح snake_case)،
-- فيُستبدل القيد بفحص صيغة فقط: حروف لاتينية صغيرة وأرقام وشرطة سفلية، يبدأ بحرف،
-- من 2 إلى 40 خانة — مطابقاً حرفياً لما يفرضه lib/config/profile.ts عند التحميل.
--
-- آمن على قاعدة قائمة: مفاتيح الركائز القديمة كلها تطابق الصيغة الجديدة، فلا يفشل
-- التحقق من الصفوف الموجودة. التحقق من أن المفتاح ضمن قائمة الملف يبقى في الكود
-- (app/(app)/content/actions.ts)، لا في قاعدة البيانات، كي لا تتطلب كل إعادة تسمية هجرة.
-- ═══════════════════════════════════════════════════════════

ALTER TABLE posts DROP CONSTRAINT IF EXISTS posts_content_pillar_chk;

ALTER TABLE posts ADD CONSTRAINT posts_content_pillar_chk
  CHECK (content_pillar IS NULL OR content_pillar ~ '^[a-z][a-z0-9_]{1,39}$');
